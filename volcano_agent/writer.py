from .llm import DEFAULT_MODEL, Usage, make_client, run_submit_loop

WRITER_SYSTEM = """You are writing chapters of a quantitative volcanology report in the style of a careful MSc thesis ("From magma compressibility to surface deformation at <volcano>"). The physical framework, tables and figures are generated by code; you write the prose.

Style:
- Formal academic English, precise and measured, third person. No marketing language, no bullet lists inside prose, no rhetorical questions.
- Every factual statement about the volcano carries an (Author, Year) citation, using ONLY the reference keys provided. Never cite anything else, except the method itself, which is cited as "Freya Mohammadian (2026)".
- Use ONLY numbers that appear in the FACTS JSON (you may round them, convert units, or express a ratio of two given numbers). Do not introduce any other number. If a quantity is not in the facts, describe it qualitatively or say it is not constrained.
- Conditional phrasing for model results: e.g. "under the adopted volatile budgets, the modelled magma is gas-undersaturated at 5 km", never "the reservoir is gas-free".
- Inputs with status "D" are generic defaults, not volcano-specific: whenever a conclusion depends on them, say so explicitly. Status "A" values are adopted representative values; "U" values are detection limits.
- If the published interpretation of the deformation source is hydrothermal, treat the magmatic calculation at that geometry as a hypothetical magmatic end-member and say so.
- Penny-crack configurations whose thin-crack condition is "violated" are stiff-walled idealisations, not sills of this volcano: never quote their r_V or pressures as predictions for the volcano; quote r_V ranges split by geometric status.
- The 10 MPa screen is a reference screening threshold used to rank configurations, not a failure criterion.
- The cavity-volume change and overpressure needed for a given uplift are fixed by the elastic problem; the injected magma volume depends on the volatile state, datum and compressibility branch. Spatial wavelength constrains depth within a given source model; amplitude is non-unique.
- Formatting: plain text paragraphs separated by a blank line. Subsection headings on their own line starting with "## ". Chemical formulas and symbols with <sub>/<sup> tags, e.g. H<sub>2</sub>O, CO<sub>2</sub>, r<sub>V</sub>, β<sub>m</sub>, 10<sup>6</sup> m<sup>3</sup>. Italic with <i>..</i>. No other markup, no Markdown tables.
Finish by calling the submit tool exactly once."""

