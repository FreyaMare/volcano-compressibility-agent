def _schema(keys: dict) -> dict:
    return {"type": "object", "properties": {k: {"type": "string", "description": d} for k, d in keys.items()},
            "required": list(keys)}


def write_chapters(ds, facts: dict, api_key: Optional[str] = None, model: str = DEFAULT_MODEL,
                   on_event: Callable[[str], None] | None = None, usage: Usage | None = None) -> dict:
    say = on_event or (lambda s: None)
    client = make_client(api_key)
    refs = [r.key for r in ds.references]
    notes = json.dumps(ds.narrative, ensure_ascii=False, indent=1)
    facts_s = json.dumps(facts, ensure_ascii=False, separators=(",", ":"))
    common = (f"VOLCANO: {ds.name}\n\nREFERENCE KEYS YOU MAY CITE:\n{json.dumps(refs, ensure_ascii=False)}\n\n"
              f"RESEARCH NOTES (cited summaries gathered from the literature):\n{notes}\n\n"
              f"FACTS (all numbers you may use):\n{facts_s}\n")
    out = {}
    say("Writing the abstract, introduction and the volcanic-system chapter")
    out.update(run_submit_loop(client, model=model, system=WRITER_SYSTEM,
                               user=[{"type": "text", "text": common, "cache_control": {"type": "ephemeral"}},
                                     {"type": "text", "text": "Write the following sections:\n" +
                                      "\n".join(f"- {k}: {v}" for k, v in PART_A.items())}],
                               force_submit=True,
                               submit_name="submit_sections", submit_description="Submit the written sections.",
                               submit_schema=_schema(PART_A), on_event=say, usage=usage, max_tokens=32000))
    say("Writing the results, discussion and conclusions")
    out.update(run_submit_loop(client, model=model, system=WRITER_SYSTEM,
                               user=[{"type": "text", "text": common, "cache_control": {"type": "ephemeral"}},
                                     {"type": "text", "text": "Write the following sections:\n" +
                                      "\n".join(f"- {k}: {v}" for k, v in PART_B.items())}],
                               force_submit=True,
                               submit_name="submit_sections", submit_description="Submit the written sections.",
                               submit_schema=_schema(PART_B), on_event=say, usage=usage, max_tokens=32000))
    return out


def offline_chapters(ds, facts: dict) -> dict:
    """Plain, factual placeholder text used when no API key is given (offline demo)."""
    cfg = facts["configurations"]
    lv = ", ".join(f"{L['name']} ({L['depth_km']['value']} km, {L['resident'].lower()})" for L in facts["inputs"]["levels"])
    sat = [s for s in facts["magmatic_states"] if s["role"] == "resident" and s["saturated"]]
    txt = {k: "" for k in list(PART_A) + list(PART_B)}
    txt["abstract"] = (f"This report applies the seven-step compressibility-to-deformation chain to {ds.name}. "
                       f"The modelled storage levels are {lv}. "
                       f"Under the adopted volatile budgets, {len(sat)} of the resident magmas are gas-saturated at their storage pressure. "
                       "[Offline mode: the narrative chapters are written by the language model when an API key is supplied; "
                       "all tables and figures below are complete.]")
    for k, v in ds.narrative.items():
        if k in ("setting", "history"):
            txt["ch2_setting"] += v + "\n\n"
        elif k == "plumbing":
            txt["ch2_plumbing"] += v + "\n\n"
        elif k.startswith("volatiles"):
            txt["ch2_volatiles"] += v + "\n\n"
        elif k in ("unrest", "deformation", "hydrothermal"):
            txt["ch2_unrest"] += v + "\n\n"
        elif k == "magma_series":
            txt["ch2_magmas"] += v + "\n\n"
    rv = [c["rV"] for c in cfg]
    txt["res_partitioning"] = f"Across all configurations r<sub>V</sub> ranges from {min(rv):.3g} to {max(rv):.3g} (see Table 5.2 for the geometric status of each)."
    return txt
